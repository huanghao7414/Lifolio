-- Apply after 003, including on databases where 003 has already run.
-- The backend uses service_role; browser/mobile clients use authenticated API routes.
BEGIN;

-- A stable tie-breaker is required when several messages have the same timestamp.
ALTER TABLE public.chat_messages
  ADD COLUMN IF NOT EXISTS sequence BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE public.chat_messages
  ALTER COLUMN created_at SET DEFAULT clock_timestamp();
CREATE INDEX IF NOT EXISTS idx_chat_messages_recent
  ON public.chat_messages (user_id, conversation_id, created_at DESC, sequence DESC);

-- A separate user_id FK alone does not prove that a message belongs to its parent owner.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.conversations'::regclass
      AND conname = 'conversations_id_user_id_key'
  ) THEN
    ALTER TABLE public.conversations
      ADD CONSTRAINT conversations_id_user_id_key UNIQUE (id, user_id);
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.chat_messages'::regclass
      AND conname = 'chat_messages_conversation_owner_fkey'
  ) THEN
    ALTER TABLE public.chat_messages
      ADD CONSTRAINT chat_messages_conversation_owner_fkey
      FOREIGN KEY (conversation_id, user_id)
      REFERENCES public.conversations (id, user_id) ON DELETE CASCADE;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.touch_conversation_on_message()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  UPDATE public.conversations
     SET message_count = message_count + 1,
         last_message_at = GREATEST(last_message_at, NEW.created_at),
         updated_at = clock_timestamp()
   WHERE id = NEW.conversation_id AND user_id = NEW.user_id;
  RETURN NEW;
END;
$$;

-- RLS remains defense in depth, but ciphertext and trusted chat history are backend-only.
-- In particular users must not bypass encryption or forge persisted assistant messages
-- with direct PostgREST table writes.
REVOKE ALL ON public.llm_configs, public.chat_messages, public.conversations FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.llm_configs, public.chat_messages, public.conversations TO service_role;
REVOKE ALL ON SEQUENCE public.chat_messages_sequence_seq FROM anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.chat_messages_sequence_seq TO service_role;

-- Earlier development versions stored unredacted provider errors. Remove those messages.
UPDATE public.llm_configs SET last_error = NULL WHERE last_error IS NOT NULL;

COMMIT;
